type Answer = [option: string, explanation: string];

function question(
  id: string, lessonId: string, category: "lectura-codigo" | "revisar-codigo",
  prompt: string, lines: string[], answers: [Answer, Answer, Answer, Answer], correctIndex: number,
): PracticeChoice {
  return {
    kind: "choice", id: "snippet-" + id, lessonId, category,
    prompt, code: lines.join("\n"),
    options: answers.map(([option]) => option),
    feedback: answers.map(([, explanation]) => explanation),
    correctIndex,
  };
}

